#!/usr/bin/env node
// Generates docs/api-routes.md from the compiled controllers' metadata (method, path, access rule, feature flag).
// Run after `pnpm --filter @medos/api build`:  node scripts/gen-route-docs.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "apps/api/package.json"));
require("reflect-metadata");
process.env.DATABASE_URL ??= "postgresql://x@127.0.0.1:5432/x";
process.env.JWT_ACCESS_SECRET ??= "doc-generation-only-secret-doc-generation";
const { CONTROLLERS } = require(join(root, "apps/api/dist/app.module.js"));
const http = require(join(root, "apps/api/dist/common/http.js"));
const METHODS = ["GET", "POST", "PUT", "DELETE", "PATCH"];

const rows = [];
for (const C of CONTROLLERS) {
  const base = String(Reflect.getMetadata("path", C) ?? "");
  const classFeature = Reflect.getMetadata("requiredFeature", C);
  for (const name of Object.getOwnPropertyNames(C.prototype)) {
    const h = C.prototype[name];
    if (name === "constructor" || typeof h !== "function") continue;
    const m = Reflect.getMetadata("method", h);
    if (m === undefined) continue;
    const sub = String(Reflect.getMetadata("path", h) ?? "");
    const path = `/api/v1/${[base, sub].filter(Boolean).join("/")}`.replace(/\/+/g, "/");
    const perms = Reflect.getMetadata(http.REQUIRED_PERMISSIONS, h);
    const access = Reflect.getMetadata(http.IS_PUBLIC, h) ? "public" : Reflect.getMetadata(http.ANY_AUTHENTICATED, h) ? "any signed-in user (checked in service)" : (perms ?? []).join(" + ");
    rows.push({ group: C.name.replace(/Controller$/, ""), method: METHODS[m], path, access, feature: Reflect.getMetadata("requiredFeature", h) ?? classFeature ?? "" });
  }
}
rows.sort((a, b) => a.group.localeCompare(b.group) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
let md = "# API routes\n\nGenerated by `node scripts/gen-route-docs.mjs` from the controllers. Do not edit by hand.\nAll paths are under `/api/v1`. Every route either is public, accepts any signed-in user (with the real check in the service), or requires the listed permission(s); a route-scan test fails the build if a route declares none of these.\n";
let group = "";
for (const r of rows) {
  if (r.group !== group) { group = r.group; md += `\n## ${group}\n\n| Method | Path | Access | Module flag |\n|---|---|---|---|\n`; }
  md += `| ${r.method} | \`${r.path.replace("/api/v1", "")}\` | ${r.access} | ${r.feature} |\n`;
}
writeFileSync(join(root, "docs/api-routes.md"), md);
console.log(`Wrote docs/api-routes.md (${rows.length} routes)`);
